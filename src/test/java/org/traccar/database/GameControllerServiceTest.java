package org.traccar.database;

import jakarta.ws.rs.BadRequestException;
import jakarta.ws.rs.WebApplicationException;
import org.h2.jdbcx.JdbcDataSource;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;

import java.time.Clock;
import java.time.Instant;
import java.time.ZoneId;
import java.util.List;
import java.util.UUID;
import java.util.concurrent.CountDownLatch;
import java.util.concurrent.Executors;
import java.util.concurrent.Future;
import java.util.concurrent.TimeUnit;

import static org.junit.jupiter.api.Assertions.*;

public class GameControllerServiceTest {

    private static final String A = "instance-a-0001";
    private static final String B = "instance-b-0002";

    private static final class MutableClock extends Clock {
        private Instant now = Instant.parse("2026-05-01T10:00:00Z");

        @Override
        public ZoneId getZone() {
            return ZoneId.of("UTC");
        }

        @Override
        public Clock withZone(ZoneId zone) {
            return this;
        }

        @Override
        public Instant instant() {
            return now;
        }

        void advance(long seconds) {
            now = now.plusSeconds(seconds);
        }
    }

    private final MutableClock clock = new MutableClock();
    private JdbcDataSource source;
    private GameControllerService service;

    @BeforeEach
    void setup() throws Exception {
        source = new JdbcDataSource();
        source.setURL("jdbc:h2:mem:" + UUID.randomUUID() + ";DB_CLOSE_DELAY=-1");
        try (var connection = source.getConnection(); var statement = connection.createStatement()) {
            statement.execute("CREATE TABLE tc_users(id INT PRIMARY KEY, name VARCHAR(128), email VARCHAR(128))");
            statement.execute("INSERT INTO tc_users VALUES(1,'Alice','a@x'),(2,'','b@x')");
            statement.execute("CREATE TABLE tc_game_sessions(id BIGINT PRIMARY KEY)");
            statement.execute("INSERT INTO tc_game_sessions VALUES(7)");
            statement.execute("CREATE TABLE tc_game_controller(id INT PRIMARY KEY, epoch BIGINT NOT NULL,"
                    + " state VARCHAR(16) NOT NULL, userid INT REFERENCES tc_users(id) ON DELETE SET NULL,"
                    + " userlabel VARCHAR(128), instanceid VARCHAR(64), label VARCHAR(128),"
                    + " gamesessionid BIGINT REFERENCES tc_game_sessions(id) ON DELETE SET NULL,"
                    + " acquiredat TIMESTAMP(3), renewedat TIMESTAMP(3), expiresat TIMESTAMP(3), endedat TIMESTAMP(3))");
            statement.execute("INSERT INTO tc_game_controller(id,epoch,state) VALUES(1,0,'free')");
            statement.execute("CREATE TABLE tc_game_requests(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"
                    + " gamesessionid BIGINT NOT NULL, type VARCHAR(32) NOT NULL, requesteruserid INT,"
                    + " requesterlabel VARCHAR(128), requesterrole VARCHAR(16) NOT NULL, targetdeviceid INT,"
                    + " targetlabel VARCHAR(128), baserevision BIGINT, parameters VARCHAR(1024) NOT NULL,"
                    + " status VARCHAR(16) NOT NULL, approvalrequired BOOLEAN, message VARCHAR(512),"
                    + " detail VARCHAR(512), epoch BIGINT, createdat TIMESTAMP(3) NOT NULL,"
                    + " expiresat TIMESTAMP(3) NOT NULL, decidedat TIMESTAMP(3), completedat TIMESTAMP(3),"
                    + " updatedat TIMESTAMP(3) NOT NULL)");
            statement.execute("CREATE TABLE tc_game_session_status(gamesessionid BIGINT PRIMARY KEY,"
                    + " revision BIGINT NOT NULL, document CLOB NOT NULL, updatedat TIMESTAMP(3) NOT NULL)");
            statement.execute("CREATE TABLE tc_game_jokers(gamesessionid BIGINT NOT NULL, deviceid INT NOT NULL,"
                    + " type VARCHAR(32) NOT NULL, granted INT NOT NULL, used INT NOT NULL, updatedat TIMESTAMP(3) NOT NULL,"
                    + " PRIMARY KEY(gamesessionid,deviceid,type))");
            statement.execute("CREATE TABLE tc_game_joker_reservations(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"
                    + " gamesessionid BIGINT NOT NULL, deviceid INT NOT NULL, type VARCHAR(32) NOT NULL, requestid BIGINT,"
                    + " status VARCHAR(16) NOT NULL, details VARCHAR(2048) NOT NULL, createdat TIMESTAMP(3) NOT NULL,"
                    + " updatedat TIMESTAMP(3) NOT NULL)");
            statement.execute("CREATE TABLE tc_game_joker_ledger(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"
                    + " gamesessionid BIGINT NOT NULL, deviceid INT NOT NULL, type VARCHAR(32) NOT NULL,"
                    + " kind VARCHAR(16) NOT NULL, quantity INT NOT NULL, requestid BIGINT, reservationid BIGINT,"
                    + " actor VARCHAR(128), detail VARCHAR(512), occurredat TIMESTAMP(3) NOT NULL)");
            statement.execute("CREATE TABLE tc_game_controller_history(id BIGINT GENERATED BY DEFAULT AS IDENTITY"
                    + " PRIMARY KEY, epoch BIGINT NOT NULL, event VARCHAR(32) NOT NULL, userid INT, userlabel VARCHAR(128),"
                    + " instanceid VARCHAR(64), label VARCHAR(128), gamesessionid BIGINT, detail VARCHAR(512),"
                    + " occurredat TIMESTAMP(3) NOT NULL)");
        }
        service = new GameControllerService(source, clock, 30, 5);
    }

    private static int status(Throwable error) {
        return ((WebApplicationException) error).getResponse().getStatus();
    }

    private List<String> events() throws Exception {
        return service.history(null, 0).items().stream().map(GameControllerService.HistoryEntry::event)
                .toList().reversed();
    }

    @Test
    void acquireIsExclusiveAndIdempotentForTheHolder() throws Exception {
        var first = service.acquire(1, A, "Laptop");
        assertTrue(first.acquired());
        assertEquals(1, first.lease().epoch());
        assertTrue(first.lease().active());
        assertEquals("Alice", first.lease().holder().userLabel());
        assertEquals(30, first.lease().leaseSeconds());
        assertEquals(5, first.lease().renewSeconds());

        var repeat = service.acquire(1, A, "Laptop");
        assertFalse(repeat.acquired());
        assertEquals(1, repeat.lease().epoch());

        // Same account on another PC, and another operator, are both refused while the lease is active.
        assertEquals(423, status(assertThrows(WebApplicationException.class, () -> service.acquire(1, B, "PC"))));
        assertEquals(423, status(assertThrows(WebApplicationException.class, () -> service.acquire(2, B, "PC"))));
        assertThrows(BadRequestException.class, () -> service.acquire(1, "bad id", "PC"));
        assertEquals(List.of("acquired"), events());
    }

    @Test
    void renewKeepsTheEpochUntilExpiry() throws Exception {
        long epoch = service.acquire(1, A, "Laptop").lease().epoch();
        clock.advance(20);
        var renewed = service.renew(1, epoch, A);
        assertEquals(epoch, renewed.epoch());
        assertEquals("2026-05-01T10:00:50Z", renewed.expiresAt());
        assertEquals(423, status(assertThrows(WebApplicationException.class, () -> service.renew(1, epoch, B))));
        assertEquals(423, status(assertThrows(WebApplicationException.class, () -> service.renew(2, epoch, A))));

        clock.advance(31);
        assertEquals("expired", service.status().state());
        assertFalse(service.status().active());
        assertEquals(423, status(assertThrows(WebApplicationException.class, () -> service.renew(1, epoch, A))));
        assertEquals(423, status(assertThrows(WebApplicationException.class, () -> service.check(1, epoch))));
        assertTrue(service.recordExpiry());
        assertFalse(service.recordExpiry());

        // Re-acquiring after expiry starts a new epoch; the old one stays rejected.
        var again = service.acquire(1, A, "Laptop");
        assertEquals(epoch + 1, again.lease().epoch());
        assertEquals(423, status(assertThrows(WebApplicationException.class, () -> service.check(1, epoch))));
        assertEquals(epoch + 1, service.check(1, epoch + 1).epoch());
        assertEquals(List.of("acquired", "expired", "acquired"), events());
    }

    @Test
    void takeoverFencesThePreviousHolder() throws Exception {
        long first = service.acquire(1, A, "Laptop").lease().epoch();
        var takeover = service.takeover(2, B, "Desk");
        assertEquals(first + 1, takeover.lease().epoch());
        assertEquals("b@x", takeover.lease().holder().userLabel());
        assertEquals(423, status(assertThrows(WebApplicationException.class, () -> service.check(1, first))));
        assertEquals(423, status(assertThrows(WebApplicationException.class, () -> service.renew(1, first, A))));
        // The new epoch belongs to the new operator only.
        assertEquals(423, status(assertThrows(WebApplicationException.class, () -> service.check(1, first + 1))));
        assertEquals(List.of("acquired", "takenOver", "takeover"), events());

        // Releasing with the old epoch changes nothing; with the current one it frees the lease.
        assertTrue(service.release(1, first).active());
        assertFalse(service.release(2, first + 1).active());
        assertEquals("released", service.status().state());
        assertEquals(423, status(assertThrows(WebApplicationException.class, () -> service.check(2, first + 1))));
    }

    @Test
    void epochKeepsIncreasingAcrossServerRestarts() throws Exception {
        long epoch = service.acquire(1, A, "Laptop").lease().epoch();
        // A new service instance reads the persisted row, as after a restart.
        service = new GameControllerService(source, clock, 30, 5);
        assertTrue(service.endAfterRestart());
        assertFalse(service.endAfterRestart());
        assertEquals("restarted", service.status().state());
        assertEquals(423, status(assertThrows(WebApplicationException.class, () -> service.renew(1, epoch, A))));
        assertEquals(epoch + 1, service.acquire(1, A, "Laptop").lease().epoch());
        assertEquals(List.of("acquired", "serverRestart", "acquired"), events());
    }

    @Test
    void executingSessionAndDriftReport() throws Exception {
        long epoch = service.acquire(1, A, "Laptop").lease().epoch();
        assertEquals(7L, service.setExecuting(1, epoch, 7L).gameSessionId());
        assertEquals(7L, service.executingSessionId());
        assertNull(service.setExecuting(1, epoch, null).gameSessionId());
        assertEquals(423, status(assertThrows(WebApplicationException.class,
                () -> service.setExecuting(1, epoch + 5, 7L))));
        service.release(1, epoch);
        assertNull(service.executingSessionId());

        service.recordUnfencedEdit(2, "PUT /api/devices/101");
        var acquisition = service.acquire(1, A, "Laptop");
        assertEquals(1, acquisition.drift().size());
        assertEquals("PUT /api/devices/101", acquisition.drift().getFirst().detail());
        service.release(1, acquisition.lease().epoch());
        assertTrue(service.acquire(1, A, "Laptop").drift().isEmpty());
    }

    @Test
    void anInFlightFencedRequestCompletesBeforeATakeover() throws Exception {
        long epoch = service.acquire(1, A, "Laptop").lease().epoch();
        long stamp = service.lockShared();
        service.check(1, epoch);
        var executor = Executors.newSingleThreadExecutor();
        try {
            CountDownLatch started = new CountDownLatch(1);
            Future<GameControllerService.Acquisition> takeover = executor.submit(() -> {
                started.countDown();
                return service.takeover(2, B, "Desk");
            });
            assertTrue(started.await(5, TimeUnit.SECONDS));
            Thread.sleep(200);
            assertFalse(takeover.isDone(), "Takeover must wait for the in-flight request");
            assertEquals(epoch, service.status().epoch());
            service.unlockShared(stamp);
            assertEquals(epoch + 1, takeover.get(5, TimeUnit.SECONDS).lease().epoch());
        } finally {
            executor.shutdownNow();
        }
    }
}
