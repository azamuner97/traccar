    private String query(String sql) throws Exception {
        try (var connection = source.getConnection(); var statement = connection.createStatement();
             var rows = statement.executeQuery(sql)) {
            return rows.next() ? rows.getString(1) : null;
        }
    }

    @Test
    void deliveryWritesPositionsAndIsIdempotent() throws Exception {
        var delivery = new GameEffectsService.Delivery("delivery-0001",
                List.of(position("mirror-1", null), new GameEffectsService.PositionInput(
                        900L, null, 0.0, 0.0, null, Map.of("caught", "1,2"))),
                new GameEffectsService.RuntimeInput(1L, mapper.readTree("""
                        {"game_status":{"speedhunt_runs":{"run":{
                          "participant_id":201,"status":"running","started_at":"2026-05-01T10:00:00Z"}}}}
                        """)),
                null, null, List.of(new GameSessionService.LogInput("operation", "2026-05-01T10:00:00Z", "ping")));
        var applied = apply(delivery);
        assertFalse(applied.outcome().replayed());
        assertEquals(2, applied.outcome().positions().size());
        assertTrue(applied.outcome().positions().stream().allMatch(GameEffectsService.PositionOutcome::latest));
        assertEquals(2L, applied.outcome().runtimeRevision());
        assertTrue(applied.speedhuntHistoryChanged());
        assertEquals(2, applied.latest().size());
        assertEquals("osmand", applied.latest().getFirst().getProtocol());
        assertEquals("still", applied.latest().getFirst().getAttributes().get("activity"));
        assertEquals("1,2", applied.latest().get(1).getAttributes().get("caught"));
        assertEquals(query("SELECT MAX(id) FROM tc_positions WHERE deviceid = 201"),
                query("SELECT positionid FROM tc_devices WHERE id = 201"));

        var replay = apply(delivery);
        assertTrue(replay.outcome().replayed());
        assertFalse(replay.speedhuntHistoryChanged());
        assertTrue(replay.latest().isEmpty());
        assertEquals(applied.outcome().positions(), replay.outcome().positions());
        assertEquals("2", query("SELECT COUNT(*) FROM tc_positions"));
        assertEquals("1", query("SELECT COUNT(*) FROM tc_game_session_logs"));
        assertEquals(2L, sessions.get(sessionId).runtimeRevision());

        var different = new GameEffectsService.Delivery("delivery-0001", List.of(position("mirror-2", null)),
                null, null, null, null);
        assertEquals(409, assertThrows(WebApplicationException.class, () -> apply(different))
                .getResponse().getStatus());
    }

    @Test
    void olderFixTimesAreStoredButDoNotBecomeLatest() throws Exception {
        Instant now = Instant.now().truncatedTo(ChronoUnit.SECONDS);
        apply(new GameEffectsService.Delivery("delivery-0002",
                List.of(position("mirror-2", now.toString())), null, null, null, null));
        var older = apply(new GameEffectsService.Delivery("delivery-0003",
                List.of(position("mirror-2", now.minusSeconds(90).toString())), null, null, null, null));
        assertFalse(older.outcome().positions().getFirst().latest());
        assertTrue(older.latest().isEmpty());
        assertEquals(older.outcome().positions().getFirst().deviceId(), 202);
        assertEquals(query("SELECT MIN(id) FROM tc_positions"), query("SELECT positionid FROM tc_devices WHERE id = 202"));
    }

    @Test
    void deliveriesWithinOneSecondBecomeLatestInOrder() throws Exception {
        Instant second = Instant.now().truncatedTo(ChronoUnit.SECONDS).minusSeconds(10);
        var first = apply(new GameEffectsService.Delivery("delivery-0009",
                List.of(position("mirror-1", second.plusMillis(600).toString())), null, null, null, null));
        // Stored with a rounded x.6 s (x+1), the x.9 s ping would compare as older and stay hidden.
        var next = apply(new GameEffectsService.Delivery("delivery-0010",
                List.of(position("mirror-1", second.plusMillis(900).toString())), null, null, null, null));
        assertTrue(first.outcome().positions().getFirst().latest());
        assertTrue(next.outcome().positions().getFirst().latest());
        assertEquals(1, next.latest().size());
        assertEquals(second.toString(), next.outcome().positions().getFirst().fixTime());
        assertEquals(second, next.latest().getFirst().getFixTime().toInstant());
        assertEquals(String.valueOf(next.outcome().positions().getFirst().positionId()),
                query("SELECT positionid FROM tc_devices WHERE id = 201"));
        try (var connection = source.getConnection(); var statement = connection.createStatement();
             var rows = statement.executeQuery("SELECT fixtime FROM tc_positions WHERE deviceid = 201 ORDER BY id")) {
            while (rows.next()) {
                assertEquals(second, rows.getTimestamp(1).toInstant());
            }
        }

        // A fix from the previous second is still older: stored, but not latest.
        var older = apply(new GameEffectsService.Delivery("delivery-0011",
                List.of(position("mirror-1", second.minusMillis(1).toString())), null, null, null, null));
        assertFalse(older.outcome().positions().getFirst().latest());
        assertTrue(older.latest().isEmpty());
        assertEquals(String.valueOf(next.outcome().positions().getFirst().positionId()),
                query("SELECT positionid FROM tc_devices WHERE id = 201"));
    }

