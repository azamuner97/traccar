    @Test
    void pushesAreQueuedOnceSentAfterCommitAndUncertainAfterACrash() throws Exception {
        var state = notifications.initialize(900);
        var alert = new GameNotificationService.Alert("alert-1", "speedhunt", "session",
                "2026-05-01T10:00:00.000Z", "UTC", "Speedhunt started", null, null);
        var delivery = new GameEffectsService.Delivery("delivery-0005", List.of(),
                null, new GameEffectsService.NotificationInput(900L, state.generation(), List.of(alert)),
                List.of(new GameEffectsService.PushInput(10L, "Game", "Speedhunt started", null, "alert-1"),
                        new GameEffectsService.PushInput(11L, "Game", "Speedhunt started", null, null)),
                null);
        var applied = apply(delivery);
        assertTrue(applied.sessionNotified());
        assertEquals(List.of(new GameEffectsService.AlertOutcome("alert-1", true)), applied.outcome().alerts());
        assertEquals(1, applied.queuedPushes().size());
        assertEquals("rejected", applied.outcome().pushes().get(1).status());

        var outbox = new GamePushOutbox(source, (userId, notificator, subject, message) ->
                sent.add(userId + ":" + notificator + ":" + message));
        assertEquals(1, outbox.sendQueued());
        assertEquals(0, outbox.sendQueued());
        assertEquals(List.of("10:traccar:Speedhunt started"), sent);
        var replay = apply(delivery);
        assertEquals(GamePushOutbox.SENT, replay.outcome().pushes().getFirst().status());
        assertEquals(0, outbox.sendQueued());

        // The same alert archived by a later delivery is not pushed again.
        var later = apply(new GameEffectsService.Delivery("delivery-0006", List.of(), null,
                new GameEffectsService.NotificationInput(900L, state.generation(), List.of(alert)),
                List.of(new GameEffectsService.PushInput(10L, "Game", "Speedhunt started", null, "alert-1")),
                null));
        assertEquals("skipped", later.outcome().pushes().getFirst().status());
        assertTrue(later.queuedPushes().isEmpty());

        // A crash between "attempting" and the outcome leaves the push uncertain; it is never retried.
        apply(new GameEffectsService.Delivery("delivery-0007", List.of(), null, null,
                List.of(new GameEffectsService.PushInput(10L, "Game", "Caught", null, null)), null));
        try (var connection = source.getConnection(); var statement = connection.createStatement()) {
            statement.execute("UPDATE tc_game_push_outbox SET status = 'attempting' WHERE status = 'queued'");
        }
        assertEquals(1, outbox.markInterrupted());
        assertEquals(0, outbox.sendQueued());
        assertEquals("uncertain", query("SELECT status FROM tc_game_push_outbox ORDER BY id DESC LIMIT 1"));

        var failing = new GamePushOutbox(source, (userId, notificator, subject, message) -> {
            throw new IllegalStateException("No token");
        });
        apply(new GameEffectsService.Delivery("delivery-0008", List.of(), null, null,
                List.of(new GameEffectsService.PushInput(10L, "Game", "Again", null, null)), null));
        assertEquals(1, failing.sendQueued());
        assertEquals("failed", query("SELECT status FROM tc_game_push_outbox ORDER BY id DESC LIMIT 1"));
        assertEquals("No token", query("SELECT detail FROM tc_game_push_outbox ORDER BY id DESC LIMIT 1"));
    }

    @Test
    void ownedResourcesComeFromStoredMappings() throws Exception {
        var owned = sessions.owned();
        assertTrue(owned.devices().containsAll(List.of(100L, 201L, 202L, 900L)));
        assertTrue(owned.users().contains(10L));
        assertFalse(owned.devices().contains(1L));
        assertEquals(java.util.Set.of(10L), sessions.memberUserIds(sessionId));
    }
