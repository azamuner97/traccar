package org.traccar.database;

import com.fasterxml.jackson.databind.ObjectMapper;
import jakarta.ws.rs.BadRequestException;
import jakarta.ws.rs.WebApplicationException;
import org.h2.jdbcx.JdbcDataSource;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.traccar.model.Device;
import org.traccar.model.User;
import org.traccar.helper.ReflectionCache;
import org.traccar.storage.query.Columns;

import java.time.Instant;
import java.util.List;
import java.util.UUID;
import java.util.concurrent.Executors;

import static org.junit.jupiter.api.Assertions.*;

public class GameNotificationServiceTest {
    private JdbcDataSource source;
    private GameNotificationService service;

    @BeforeEach
    void setup() throws Exception {
        source = new JdbcDataSource();
        source.setURL("jdbc:h2:mem:" + UUID.randomUUID() + ";DB_CLOSE_DELAY=-1");
        try (var connection = source.getConnection(); var statement = connection.createStatement()) {
            statement.execute("CREATE TABLE tc_users(id INT PRIMARY KEY)");
            statement.execute("INSERT INTO tc_users(id) VALUES(10),(11)");
            statement.execute("CREATE TABLE tc_devices(id INT PRIMARY KEY, attributes VARCHAR(4000))");
            for (String column : new Columns.Exclude("id", "attributes").getColumns(Device.class, "get")) {
                Class<?> type = ReflectionCache.getProperties(Device.class, "get").get(column).type();
                String sqlType = type == boolean.class ? "BOOLEAN" : type == int.class ? "INT"
                        : type == long.class ? "BIGINT" : type == double.class ? "DOUBLE"
                        : type == java.util.Date.class ? "TIMESTAMP" : "VARCHAR(128)";
                statement.execute("ALTER TABLE tc_devices ADD " + column + " " + sqlType);
            }
            statement.execute("INSERT INTO tc_devices(id,attributes) VALUES(900, '{\"traccarToolGameState\":true}')");
            statement.execute("INSERT INTO tc_devices(id,attributes) VALUES(901, '{\"traccarToolGameState\":true}')");
            statement.execute("UPDATE tc_devices SET name='test', uniqueid=CAST(id AS VARCHAR)");
            statement.execute("ALTER TABLE tc_devices ADD CONSTRAINT unique_device UNIQUE(uniqueid)");
            statement.execute("CREATE TABLE tc_game_notifications(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"
                    + "alertid VARCHAR(64), sessiondeviceid INT REFERENCES tc_devices(id) ON DELETE CASCADE,"
                    + "generation VARCHAR(36), type VARCHAR(32), audience VARCHAR(16), occurredat TIMESTAMP(3),"
                    + "timezone VARCHAR(64), message TEXT, recipientuserid INT REFERENCES tc_users(id) ON DELETE CASCADE,"
                    + "sourcedeviceid INT, createdat TIMESTAMP(3), UNIQUE(sessiondeviceid,alertid))");
        }
        service = new GameNotificationService(source, new ObjectMapper());
    }

    private GameNotificationService.Alert alert(String id) {
        return new GameNotificationService.Alert(id, "speedhunt", "session", "2026-01-01T12:00:00.123Z",
                "Europe/Zurich", "[13:00:00] Speedhunt: Ping 2 out of 4 sent.", null, null);
    }

    @Test
    void archivePaginationDeduplicationAndReset() throws Exception {
        var state = service.initialize(900);
        assertEquals(state, service.initialize(900));
        for (int i = 0; i < 110; i++) {
            assertTrue(service.create(900, state.generation(), alert("alert" + i)).created());
        }
        assertFalse(service.create(900, state.generation(), alert("alert0")).created());
        var first = service.list(900, null, null, 0, null);
        assertEquals(100, first.items().size());
        assertTrue(first.hasMore());
        var second = service.list(900, state.generation(), first.nextCursor(), 100, null);
        assertEquals(10, second.items().size());
        assertFalse(second.hasMore());
        assertEquals("alert100", second.items().getFirst().id());
        assertTrue(service.list(901, null, null, 100, null).items().isEmpty());
        String replacement = UUID.randomUUID().toString();
        var reset = service.reset(900, state.generation(), replacement);
        assertEquals(reset, service.reset(900, state.generation(), replacement));
        assertTrue(service.list(900, replacement, null, 100, null).items().isEmpty());
        assertEquals(409, assertThrows(WebApplicationException.class,
                () -> service.create(900, state.generation(), alert("late"))).getResponse().getStatus());
    }

    @Test
    void conflictsAndMalformedRecordsDoNotMutateArchive() throws Exception {
        var state = service.initialize(900);
        service.create(900, state.generation(), alert("one"));
        var conflict = new GameNotificationService.Alert("one", "playerCaught", "session",
                "2026-01-01T12:00:00Z", "UTC", "Alice was caught", null, null);
        assertEquals(409, assertThrows(WebApplicationException.class,
                () -> service.create(900, state.generation(), conflict)).getResponse().getStatus());
        assertThrows(BadRequestException.class, () -> service.list(900, null, "-1", 100, null));
        assertThrows(BadRequestException.class, () -> service.list(900, null, null, 501, null));
        assertThrows(BadRequestException.class, () -> GameNotificationService.validate(
                new GameNotificationService.Alert("a", "speedhunt", "participants",
                        "2026-01-01T12:00:00Z", "UTC", "message", null, null)));
        assertThrows(BadRequestException.class, () -> GameNotificationService.validate(
                new GameNotificationService.Alert("a", "speedhunt", "session",
                        Instant.now().plusSeconds(120).toString(), "UTC", "message", null, null)));
        assertEquals(1, service.list(900, null, null, 100, null).items().size());
    }

    @Test
    void concurrentDuplicateInsertAndResetAreSerialized() throws Exception {
        var state = service.initialize(900);
        try (var executor = Executors.newFixedThreadPool(4)) {
            var one = executor.submit(() -> service.create(900, state.generation(), alert("one")));
            var duplicate = executor.submit(() -> service.create(900, state.generation(), alert("one")));
            assertNotEquals(one.get().created(), duplicate.get().created());
            String replacement = UUID.randomUUID().toString();
            var insertion = executor.submit(() -> {
                try {
                    return service.create(900, state.generation(), alert("racing"));
                } catch (WebApplicationException expected) {
                    assertEquals(409, expected.getResponse().getStatus());
                    return null;
                }
            });
            var reset = executor.submit(() -> service.reset(900, state.generation(), replacement));
            insertion.get();
            reset.get();
            assertTrue(service.list(900, replacement, null, 100, null).items().isEmpty());
        }
    }

    @Test
    void opaqueIdsAreCaseSensitiveAndUnsafeArchiveValuesAreRejected() throws Exception {
        var state = service.initialize(900);
        assertTrue(service.create(900, state.generation(), alert("CaseId")).created());
        assertTrue(service.create(900, state.generation(), alert("caseid")).created());
        assertFalse(service.create(900, state.generation(), alert("CaseId")).created());
        for (String zone : new String[] {"GMT+02:00", "+02:00", "SystemV/EST5EDT"}) {
            assertThrows(BadRequestException.class, () -> service.create(900, state.generation(),
                    new GameNotificationService.Alert("invalid", "speedhunt", "session",
                            "2026-01-01T12:00:00Z", zone, "message", null, null)));
        }
        assertThrows(BadRequestException.class, () -> service.create(900, state.generation(),
                new GameNotificationService.Alert("invalid", "speedhunt", "session",
                        "1900-01-01T12:00:00Z", "UTC", "message", null, null)));
        assertEquals(2, service.list(900, null, null, 100, null).items().size());
    }

    @Test
    void ordinaryDeviceSavePreservesGenerationAndDeleteCascades() throws Exception {
        var state = service.initialize(900);
        Device stale = new Device();
        stale.setId(900);
        stale.setName("setting");
        stale.setUniqueId("900");
        stale.getAttributes().put(GameNotificationService.GENERATION_ATTRIBUTE, "forged");
        stale.getAttributes().put("name", "setting");
        service.updateDevice(stale);
        assertEquals(state.generation(), service.initialize(900).generation());
        assertEquals(true, stale.getAttributes().get("traccarToolGameState"));
        stale.setUniqueId("901");
        stale.getAttributes().put("uncommitted", true);
        assertThrows(java.sql.SQLException.class, () -> service.updateDevice(stale));
        try (var connection = source.getConnection(); var statement = connection.createStatement();
                var rows = statement.executeQuery("SELECT attributes FROM tc_devices WHERE id=900")) {
            rows.next();
            assertFalse(rows.getString(1).contains("uncommitted"));
        }
        service.create(900, state.generation(), alert("one"));
        try (var connection = source.getConnection(); var statement = connection.createStatement()) {
            statement.execute("DELETE FROM tc_devices WHERE id=900");
            try (var rows = statement.executeQuery("SELECT COUNT(*) FROM tc_game_notifications")) {
                rows.next();
                assertEquals(0, rows.getInt(1));
            }
        }
    }

    @Test
    void generatedRolePolicyFailsClosed() {
        for (String role : new String[] {"player", "supporter", "hunter", "spectator"}) {
            User user = new User();
            user.getAttributes().put("traccarToolUserRole", role);
            user.getAttributes().put("traccarToolSessionDeviceId", 900);
            assertTrue(GameNotificationService.canReceive(user, 900));
            assertFalse(GameNotificationService.canReceive(user, 901));
            user.getAttributes().put("traccarToolSessionDeviceId", 900.5);
            assertFalse(GameNotificationService.canReceive(user, 900));
            user.getAttributes().put("traccarToolSessionDeviceId", 900);
            user.setAdministrator(true);
            assertFalse(GameNotificationService.canReceive(user, 900));
        }
    }

    @Test
    void targetedAlertsArePrivateAndRecipientDeletionCascades() throws Exception {
        var state = service.initialize(900);
        service.create(900, state.generation(), alert("session"));
        var first = new GameNotificationService.Alert("exit-1", "geofenceExit", "user",
                "2026-01-01T12:00:01Z", "UTC", "Hunter 1 left the area", 10L, 100L);
        var second = new GameNotificationService.Alert("exit-2", "geofenceExit", "user",
                "2026-01-01T12:00:02Z", "UTC", "Hunter 2 left the area", 11L, 101L);
        service.create(900, state.generation(), first);
        service.create(900, state.generation(), second);

        assertEquals(3, service.list(900, state.generation(), null, 100, null).items().size());
        var firstUser = service.list(900, state.generation(), null, 100, 10L).items();
        assertEquals(List.of("session", "exit-1"), firstUser.stream().map(
                GameNotificationService.Entry::id).toList());
        assertEquals(10, firstUser.getLast().recipientUserId());
        assertEquals(100, firstUser.getLast().sourceDeviceId());
        assertEquals(List.of("session", "exit-2"), service.list(
                900, state.generation(), null, 100, 11L).items().stream().map(
                        GameNotificationService.Entry::id).toList());

        try (var connection = source.getConnection(); var statement = connection.createStatement()) {
            statement.execute("DELETE FROM tc_users WHERE id=10");
        }
        assertEquals(List.of("session", "exit-2"), service.list(
                900, state.generation(), null, 100, null).items().stream().map(
                        GameNotificationService.Entry::id).toList());
    }

    @Test
    void audienceAndTargetMatrixIsStrict() {
        assertDoesNotThrow(() -> GameNotificationService.validate(alert("session")));
        assertDoesNotThrow(() -> GameNotificationService.validate(new GameNotificationService.Alert(
                "exit", "geofenceExit", "user", "2026-01-01T12:00:00Z", "UTC", "message", 10L, 100L)));
        for (GameNotificationService.Alert invalid : List.of(
                new GameNotificationService.Alert("a", "geofenceExit", "session",
                        "2026-01-01T12:00:00Z", "UTC", "message", null, null),
                new GameNotificationService.Alert("b", "speedhunt", "user",
                        "2026-01-01T12:00:00Z", "UTC", "message", 10L, 100L),
                new GameNotificationService.Alert("c", "geofenceExit", "user",
                        "2026-01-01T12:00:00Z", "UTC", "message", null, 100L),
                new GameNotificationService.Alert("d", "notificationTest", "session",
                        "2026-01-01T12:00:00Z", "UTC", "message", 10L, 100L))) {
            assertThrows(BadRequestException.class, () -> GameNotificationService.validate(invalid));
        }
    }
}
