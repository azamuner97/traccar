    @Test
    void breakAndFakeJokersNeedMirrorOnlyHunterAccess() throws Exception {
        var jokers = new GameJokerService(source);
        var rule = new GameAccessRule(source);
        sessions.updateConfig(sessionId, 1, null,
                mapper.readTree("{\"game_settings\":{\"break_duration_minutes\":15}}"));
        execute("INSERT INTO tc_groups VALUES(50,'Real',NULL),(51,'Players',50),(60,'Hunter mirrors',NULL)");
        execute("UPDATE tc_devices SET groupid = 51 WHERE id = 101");
        // Hunters see their mirrors; spectators and other roles are not limited.
        execute("INSERT INTO tc_user_group VALUES(10,60)");
        var grant = new GameJokerService.Change(101L, GameJokerService.BREAK, 1, null);

        // Inherited access through a parent group blocks break jokers; Get hunter positions are not affected.
        execute("INSERT INTO tc_user_group VALUES(11,50)");
        var refused = assertThrows(WebApplicationException.class, () -> jokers.change(sessionId, grant, "Operator"));
        assertEquals(409, status(refused));
        assertTrue(message(refused).contains("hunter2"));
        jokers.change(sessionId, new GameJokerService.Change(101L, GameJokerService.HUNTER_POSITIONS, 1, null),
                "Operator");
        execute("DELETE FROM tc_user_group WHERE userid = 11");
        // Direct access to a real participant tracker too.
        execute("INSERT INTO tc_user_device VALUES(10,102)");
        assertThrows(WebApplicationException.class, () -> jokers.change(sessionId, grant, "Operator"));
        execute("DELETE FROM tc_user_device");
        jokers.change(sessionId, grant, "Operator");

        // From now on, access that would reach a real participant tracker is refused before it is made.
        assertEquals(422, status(assertThrows(WebApplicationException.class, () -> rule.check(
                new GameAccessRule.Change(List.of(new long[] {10, 102}), List.of(), Map.of(), Map.of())))));
        assertThrows(WebApplicationException.class, () -> rule.check(
                new GameAccessRule.Change(List.of(), List.of(new long[] {11, 50}), Map.of(), Map.of())));
        // Moving a tracker into a group a hunter sees, or such a group under one, is a grant as well.
        assertThrows(WebApplicationException.class, () -> rule.check(
                new GameAccessRule.Change(List.of(), List.of(), Map.of(102L, 60L), Map.of())));
        assertThrows(WebApplicationException.class, () -> rule.check(
                new GameAccessRule.Change(List.of(), List.of(), Map.of(), Map.of(50L, 60L))));
        // Access for other users, to mirrors, or out of hunters' reach is fine.
        rule.check(new GameAccessRule.Change(List.of(new long[] {20, 102}, new long[] {10, 900}),
                List.of(new long[] {1, 50}), Map.of(101L, 50L), Map.of()));

        // Membership that would make a user with real access a hunter is refused too (not a revision conflict).
        execute("INSERT INTO tc_user_group VALUES(21,50)");
        assertEquals(422, status(assertThrows(WebApplicationException.class, () -> sessions.updateResources(
                sessionId, 2, 900L, mapper.readTree("{}"), List.of(
                        new GameSessionService.Member(10, "hunter", 1, null, "hunter1"),
                        new GameSessionService.Member(11, "hunter", 2, null, "hunter2"),
                        new GameSessionService.Member(20, "player", 1, 101L, "player1"),
                        new GameSessionService.Member(21, "hunter", 3, null, "hunter3"))))));
        assertEquals("player", requests.membership(21).role(), "nothing was saved");

        // Access the new members do not add never blocks a save (it was refused where it was made).
        execute("DELETE FROM tc_user_group WHERE userid = 21");
        execute("INSERT INTO tc_user_device VALUES(10,101)");
        assertEquals(3, sessions.updateResources(sessionId, 2, 900L, mapper.readTree("{\"renamed\":true}"),
                List.of(new GameSessionService.Member(10, "hunter", 1, null, "hunter1"),
                        new GameSessionService.Member(11, "hunter", 2, null, "hunter2"),
                        new GameSessionService.Member(20, "player", 1, 101L, "player1"),
                        new GameSessionService.Member(21, "player", 2, 102L, "player2"))).revision());
        // A new hunter with such access is still refused.
        execute("INSERT INTO tc_user_device VALUES(21,101)");
        assertEquals(422, status(assertThrows(WebApplicationException.class, () -> sessions.updateResources(
                sessionId, 3, 900L, mapper.readTree("{}"), List.of(
                        new GameSessionService.Member(10, "hunter", 1, null, "hunter1"),
                        new GameSessionService.Member(21, "hunter", 3, null, "hunter3"),
                        new GameSessionService.Member(20, "player", 1, 101L, "player1"))))));
    }

