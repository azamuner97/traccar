    private GameEffectsService.Outcome publish(String status) throws Exception {
        return deliver(null, mapper.readTree(status));
    }

    private GameEffectsService.Outcome deliver(List<GameRequestService.Completion> completions, JsonNode status)
            throws Exception {
        var delivery = new GameEffectsService.Delivery("delivery-" + UUID.randomUUID(), null, null, null, null,
                null, completions, status);
        return effects.apply(sessionId, epoch, delivery, effects.validate(delivery)).outcome();
    }

    private static int status(Throwable error) {
        return ((WebApplicationException) error).getResponse().getStatus();
    }

    private GameRequestService.Submission ping(long target, long revision) {
        return new GameRequestService.Submission("speedhuntStaticPing", target, revision, null);
    }

    @Test
    void hunterRequestsAreAuthorizedFromMembershipAndTheCurrentSpeedhunt() throws Exception {
        var hunter = requests.membership(10);
        var player = requests.membership(20);
        assertThrows(ForbiddenException.class, () -> requests.membership(1));
        assertThrows(ForbiddenException.class, () -> requests.submit(player, ping(101, 3)));
        assertThrows(BadRequestException.class, () -> requests.submit(hunter, ping(999, 3)));
        assertEquals(409, status(assertThrows(WebApplicationException.class,
                () -> requests.submit(hunter, ping(101, 2)))), "stale revision");
        assertEquals(409, status(assertThrows(WebApplicationException.class,
                () -> requests.submit(hunter, ping(102, 1)))), "caught participant");
        assertThrows(BadRequestException.class, () -> requests.submit(hunter, new GameRequestService.Submission(
                "speedhuntLivePing", 101L, 3L, mapper.readTree("{\"durationMinutes\":999}"))));

        var request = requests.submit(hunter, ping(101, 3));
        assertEquals("pending", request.status());
        assertEquals("Anna", request.targetLabel());
        assertEquals("Hunter One", request.requesterLabel());
        // Simultaneous hunters cannot queue a second action on the same participant.
        assertEquals(409, status(assertThrows(WebApplicationException.class,
                () -> requests.submit(requests.membership(11), ping(101, 3)))));

        // Shared control: the other hunter sees it; players never see speedhunt requests.
        assertEquals(1, requests.list(requests.membership(11), 0).size());
        assertTrue(requests.list(player, 0).isEmpty());
        assertThrows(ForbiddenException.class, () -> requests.cancel(requests.membership(11), request.id()));
    }

