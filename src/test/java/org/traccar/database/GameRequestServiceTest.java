    /** Arms a timetable fake through the request lifecycle; returns its reservation ID. */
    private long arm(GameRequestService.Membership owner, long entryId, double latitude) throws Exception {
        long id = requests.submit(owner, fake(entryId, latitude)).id();
        requests.claim(sessionId, id, epoch);
        deliver(List.of(new GameRequestService.Completion(id, "succeeded", "Your fake ping is armed", null)), null);
        return new GameJokerService(source).own(sessionId, owner.assignedDeviceId()).reservations().stream()
                .filter(item -> item.armed() && item.plan().path("entryId").asLong() == entryId)
                .findFirst().orElseThrow().id();
    }

    @Test
    void timetableFakesAreArmedUsedReleasedAndStayPrivate() throws Exception {
        var jokers = new GameJokerService(source);
        Instant base = clock.now.truncatedTo(java.time.temporal.ChronoUnit.MINUTES).plusSeconds(3600);
        String[] cells = {"", "2P2S", "b", "x", "47.1,8.5|2H", "2H", "2P2H", "2S2H"};
        List<GameSessionService.EntryInput> entries = new java.util.ArrayList<>();
        for (int index = 0; index < cells.length; index++) {
            entries.add(new GameSessionService.EntryInput(base.plusSeconds(600L * index).toString(), "Anna",
                    cells[index]));
        }
        entries.add(new GameSessionService.EntryInput(base.toString(), "Ben", ""));
        entries.add(new GameSessionService.EntryInput(clock.now.plusSeconds(30).toString(), "Anna", ""));
        var published = sessions.publishTimetable(sessionId, 0, mapper.readTree("[\"Time\",\"Anna\",\"Ben\"]"),
                mapper.readTree("{}"), entries);
        java.util.Map<String, Long> ids = new java.util.HashMap<>();
        for (var entry : published.entries()) {
            ids.put(entry.participant() + "@" + Instant.parse(entry.scheduledAt()), entry.id());
        }
        java.util.function.IntFunction<Long> anna = index -> ids.get("Anna@" + base.plusSeconds(600L * index));
        long tooClose = ids.get("Anna@" + clock.now.plusSeconds(30).truncatedTo(java.time.temporal.ChronoUnit.MILLIS));
        var owner = requests.membership(20);
        jokers.change(sessionId, new GameJokerService.Change(101L, GameJokerService.FAKE_TIMETABLE, 5, null),
                "Operator");

        // Only the owner's own upcoming pings that reach hunters, without an operator coordinate.
        for (int index : new int[] {1, 2, 3, 4}) {
            assertEquals(409, status(assertThrows(WebApplicationException.class,
                    () -> requests.submit(owner, fake(anna.apply(index), 47.2)))), cells[index]);
        }
        assertThrows(BadRequestException.class, () -> requests.submit(owner, fake(ids.get("Ben@" + base), 47.2)));
        assertEquals(409, status(assertThrows(WebApplicationException.class,
                () -> requests.submit(owner, fake(tooClose, 47.2)))), "too close");
        assertThrows(BadRequestException.class, () -> requests.submit(owner, fake(anna.apply(0), 91)));
        assertThrows(BadRequestException.class, () -> requests.submit(owner, new GameRequestService.Submission(
                "jokerFakeTimetable", null, null, mapper.readTree("{\"entryId\":" + anna.apply(0)
                        + ".5,\"latitude\":47.2,\"longitude\":8.5}"))), "whole entry IDs only");
        var offered = jokers.own(sessionId, 101).timetableEntries().stream()
                .map(GameJokerService.FakeEntry::entryId).toList();
        assertEquals(List.of(anna.apply(0), anna.apply(5), anna.apply(6), anna.apply(7)), offered);
        assertEquals(0, fakes(jokers, 101).reserved(), "refusals reserve nothing");

        // Approved and recorded as succeeded, the fake is armed: still reserved, not used.
        long first = arm(owner, anna.apply(0), 47.2);
        assertEquals(1, fakes(jokers, 101).reserved());
        assertEquals(0, fakes(jokers, 101).used());
        var plan = jokers.own(sessionId, 101).reservations().getFirst();
        assertNull(plan.requestId());
        assertEquals(47.2, plan.plan().get("latitude").asDouble());
        assertEquals(base.toString(), plan.plan().get("scheduledAt").asText());
        assertTrue(jokers.own(sessionId, 101).timetableEntries().getFirst().taken());
        assertEquals(409, status(assertThrows(WebApplicationException.class,
                () -> requests.submit(owner, fake(anna.apply(0), 47.3)))), "one fake per ping");

        // The owner sees the plan; hunters and other players never do.
        assertEquals(anna.apply(0), requests.status(owner).status().get("fakes").get(0).get("entryId").asLong());
        String hunterView = mapper.writeValueAsString(requests.status(requests.membership(10)));
        assertFalse(hunterView.contains("fakes") || hunterView.contains("47.2"), hunterView);
        assertEquals(0, requests.status(requests.membership(21)).status().get("fakes").size());
        assertTrue(requests.list(requests.membership(10), 0).isEmpty());

        // Delivered to hunters: used with the delivery; a repeated report changes nothing. Only the owner is
        // told that their jokers changed, so nobody else can tell that this ping was a fake.
        var fakeDelivery = new GameEffectsService.Delivery("delivery-" + UUID.randomUUID(), null, null, null, null,
                null, null, null, null, null, List.of(new GameJokerService.FakeSettlement(first, "used", "14:00")));
        var applied = effects.apply(sessionId, epoch, fakeDelivery, effects.validate(fakeDelivery));
        assertEquals(java.util.Set.of(20L), applied.jokerUsers());
        var used = applied.outcome();
        assertEquals("consumed", used.fakes().getFirst().status());
        assertEquals(1, fakes(jokers, 101).used());
        assertEquals(0, fakes(jokers, 101).reserved());
        assertEquals("skipped", deliverFakes(List.of(new GameJokerService.FakeSettlement(first, "released", null)),
                null).fakes().getFirst().status());

        // Skipped pings release the fake: reported by the Tool, or the ping no longer reaches hunters.
        long skipped = arm(owner, anna.apply(5), 47.2);
        deliverFakes(List.of(new GameJokerService.FakeSettlement(skipped, "released", "Break")), null);
        long replaced = arm(owner, anna.apply(6), 47.2);
        entries.set(6, new GameSessionService.EntryInput(base.plusSeconds(3600).toString(), "Anna", "b"));
        sessions.publishTimetable(sessionId, published.revision(), mapper.readTree("[\"Time\",\"Anna\",\"Ben\"]"),
                mapper.readTree("{}"), entries);
        assertFalse(jokers.own(sessionId, 101).reservations().stream().anyMatch(item -> item.id() == replaced));
        assertEquals(1, fakes(jokers, 101).used());
        assertEquals(4, fakes(jokers, 101).available());

        // The owner may cancel until shortly before the ping; nobody else may.
        long cancelled = arm(owner, anna.apply(7), 47.2);
        assertThrows(ForbiddenException.class, () -> jokers.cancelFake(sessionId, 102, cancelled, "Ben"));
        assertEquals("released", jokers.cancelFake(sessionId, 101, cancelled, "Owner").status());
        assertEquals(409, status(assertThrows(WebApplicationException.class,
                () -> jokers.cancelFake(sessionId, 101, cancelled, "Owner"))));

        // Catching the owner releases an armed fake.
        arm(owner, anna.apply(5), 47.2);
        deliverFakes(null, List.of(101L));
        assertEquals(0, fakes(jokers, 101).reserved());
        assertEquals(1, fakes(jokers, 101).used());
        var kinds = jokers.ledger(sessionId, 0).stream().filter(item -> item.type().equals("fakeTimetable"))
                .map(GameJokerService.LedgerEntry::kind).toList();
        assertEquals(List.of("release", "arm", "reserve", "release", "arm", "reserve", "release", "arm", "reserve",
                "release", "arm", "reserve", "use", "arm", "reserve", "grant"), kinds);
    }

