    @Test
    void jokersAreGrantedReservedConsumedAndReleased() throws Exception {
        var jokers = new GameJokerService(source);
        var player = requests.membership(20);
        var hunterPositions = new GameRequestService.Submission("jokerHunterPositions", null, null, null);
        assertEquals(409, status(assertThrows(WebApplicationException.class,
                () -> requests.submit(player, hunterPositions))), "nothing granted yet");
        assertThrows(ForbiddenException.class, () -> requests.submit(requests.membership(10), hunterPositions));
        assertThrows(BadRequestException.class, () -> jokers.change(sessionId,
                new GameJokerService.Change(101L, "teleport", 1, null), "Operator"), "unknown joker type");
        assertThrows(BadRequestException.class, () -> jokers.change(sessionId,
                new GameJokerService.Change(999L, GameJokerService.HUNTER_POSITIONS, 1, null), "Operator"));

        jokers.change(sessionId, new GameJokerService.Change(101L, GameJokerService.HUNTER_POSITIONS, 2, "start"),
                "Operator");
        var request = requests.submit(player, hunterPositions);
        assertEquals(101L, request.targetDeviceId(), "jokers are always for the requester");
        assertEquals(409, status(assertThrows(WebApplicationException.class,
                () -> requests.submit(player, hunterPositions))), "one open request per joker");
        var reserved = hunterPositions(jokers, 101);
        assertEquals(1, reserved.reserved());
        assertEquals(1, reserved.available());
        assertEquals(request.id(), jokers.overview(sessionId).reservations().getFirst().requestId());
        assertEquals(reserved, jokers.own(sessionId, 101).inventories().stream()
                .filter(item -> item.type().equals(GameJokerService.HUNTER_POSITIONS)).findFirst().orElseThrow());
        // Revoking never touches reserved uses.
        assertEquals(409, status(assertThrows(WebApplicationException.class, () -> jokers.change(sessionId,
                new GameJokerService.Change(101L, GameJokerService.HUNTER_POSITIONS, -2, null), "Operator"))));
        // Hunters never see players' joker requests.
        assertTrue(requests.list(requests.membership(10), 0).isEmpty());

        // Success consumes the reserved use.
        requests.claim(sessionId, request.id(), epoch);
        deliver(List.of(new GameRequestService.Completion(request.id(), "succeeded", "2 hunter positions sent",
                null)), null);
        var consumed = hunterPositions(jokers, 101);
        assertEquals(1, consumed.used());
        assertEquals(0, consumed.reserved());
        assertEquals(1, consumed.available());

        // Any other end releases it: rejection, cancellation, expiry.
        long rejected = requests.submit(player, hunterPositions).id();
        requests.decide(sessionId, rejected, "reject", "No", null);
        long cancelled = requests.submit(player, hunterPositions).id();
        requests.cancel(player, cancelled);
        requests.submit(player, hunterPositions);
        clock.now = clock.now.plusSeconds(121);
        requests.expire();
        clock.now = clock.now.minusSeconds(121);
        var released = hunterPositions(jokers, 101);
        assertEquals(1, released.used());
        assertEquals(1, released.available());
        var kinds = jokers.ledger(sessionId, 0).stream().map(GameJokerService.LedgerEntry::kind).toList();
        assertEquals(List.of("release", "reserve", "release", "reserve", "release", "reserve", "use", "reserve",
                "grant"), kinds);

        // A reservation without a request (an armed fake) has no request ID.
        try (var connection = source.getConnection(); var statement = connection.createStatement()) {
            statement.executeUpdate("INSERT INTO tc_game_joker_reservations (gamesessionid,deviceid,type,requestid,"
                    + "status,details,createdat,updatedat) VALUES (" + sessionId + ",102,'hunterPositions',NULL,"
                    + "'reserved','{}',CURRENT_TIMESTAMP,CURRENT_TIMESTAMP)");
        }
        var armed = jokers.own(sessionId, 102).reservations();
        assertEquals(1, armed.size());
        assertNull(armed.getFirst().requestId());
        assertEquals(1, hunterPositions(jokers, 102).reserved());
    }

    @Test
    void operatorRelaysUseAvailableJokersOrAConfirmedUseBeyondTheAllocation() throws Exception {
        var jokers = new GameJokerService(source);
        jokers.change(sessionId, new GameJokerService.Change(101L, GameJokerService.HUNTER_POSITIONS, 1, null),
                "Operator");
        var use = new GameJokerService.Use(101L, GameJokerService.HUNTER_POSITIONS, false, "Manual relay");
        // The only joker is reserved by the participant's own request: the relay must not take it.
        requests.submit(requests.membership(20),
                new GameRequestService.Submission("jokerHunterPositions", null, null, null));
        assertEquals(409, status(assertThrows(WebApplicationException.class,
                () -> deliverJokers(List.of(use), null))));
        var outcome = deliverJokers(List.of(new GameJokerService.Use(101L, GameJokerService.HUNTER_POSITIONS, true,
                "Manual relay")), null);
        assertTrue(outcome.jokers().getFirst().overAllocated());
        var inventory = hunterPositions(jokers, 101);
        assertEquals(1, inventory.used());
        // The granted joker is still reserved; the relay's use counts beyond the allocation once realized.
        assertEquals(0, inventory.available(), "available never goes below zero");
        jokers.change(sessionId, new GameJokerService.Change(102L, GameJokerService.HUNTER_POSITIONS, 1, null),
                "Operator");
        deliverJokers(List.of(new GameJokerService.Use(102L, GameJokerService.HUNTER_POSITIONS, false, "Relay")),
                null);
        deliverJokers(List.of(new GameJokerService.Use(102L, GameJokerService.HUNTER_POSITIONS, true, "Relay")),
                null);
        assertEquals(1, hunterPositions(jokers, 102).overAllocated());
        assertEquals(2, hunterPositions(jokers, 102).used());

        // A caught participant's open requests end and their reservation is released.
        deliverJokers(null, List.of(101L));
        var request = requests.list(requests.membership(20), 0).getFirst();
        assertEquals("cancelled", request.status());
        assertEquals(0, hunterPositions(jokers, 101).reserved());
        assertEquals("overuse", jokers.ledger(sessionId, 0).stream()
                .filter(entry -> entry.kind().contains("use")).findFirst().orElseThrow().kind());
    }

